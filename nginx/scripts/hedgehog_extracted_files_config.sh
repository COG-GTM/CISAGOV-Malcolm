# Render the runtime nginx configuration for the /hh-extracted-files/<sensor>/ route
# (see nginx_hedgehog_extracted_files_location.conf) from environment variables:
#
#   NGINX_HEDGEHOG_EXTRACTED_FILES_HOSTS      - space-separated allowlist of Hedgehog sensor
#                                               hostnames/IP addresses (a leading "*." permits
#                                               a whole domain); empty denies every request
#   NGINX_HEDGEHOG_EXTRACTED_FILES_SSL_VERIFY - "true" to verify the sensor's TLS certificate
#                                               against the trusted CA bundle
#
# Usage: hedgehog_extracted_files_config.sh <hosts map output file> <ssl include output file> <trusted CA bundle>

set -e

HOSTS_MAP_CONF="$1"
SSL_CONF="$2"
CA_BUNDLE="$3"

if [[ -z "$HOSTS_MAP_CONF" ]] || [[ -z "$SSL_CONF" ]] || [[ -z "$CA_BUNDLE" ]]; then
  echo "usage: $(basename "$0") <hosts map output file> <ssl include output file> <trusted CA bundle>" >&2
  exit 2
fi

HOST_ENTRY_REGEX='^(\*\.)?[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$'

{
  echo "# generated by $(basename "$0") from NGINX_HEDGEHOG_EXTRACTED_FILES_HOSTS; do not edit"
  echo 'map $hh_extracted_files_host $hh_extracted_files_host_allowed {'
  echo '  hostnames;'
  echo '  default 0;'
  for HOST in ${NGINX_HEDGEHOG_EXTRACTED_FILES_HOSTS:-}; do
    if [[ ! "$HOST" =~ $HOST_ENTRY_REGEX ]]; then
      echo "NGINX_HEDGEHOG_EXTRACTED_FILES_HOSTS entry is not a valid hostname, IP address, or *.domain: $HOST" >&2
      exit 1
    fi
    echo "  \"$HOST\" 1;"
  done
  echo '}'
} > "${HOSTS_MAP_CONF}.tmp"
mv -f "${HOSTS_MAP_CONF}.tmp" "$HOSTS_MAP_CONF"

{
  echo "# generated by $(basename "$0") from NGINX_HEDGEHOG_EXTRACTED_FILES_SSL_VERIFY; do not edit"
  case "${NGINX_HEDGEHOG_EXTRACTED_FILES_SSL_VERIFY:-false}" in
    1|true|yes|on)
      echo 'proxy_ssl_verify on;'
      echo 'proxy_ssl_verify_depth 5;'
      echo "proxy_ssl_trusted_certificate $CA_BUNDLE;"
      echo 'proxy_ssl_server_name on;'
      echo 'proxy_ssl_name $hh_extracted_files_host;'
      ;;
    *)
      echo 'proxy_ssl_verify off;'
      ;;
  esac
} > "${SSL_CONF}.tmp"
mv -f "${SSL_CONF}.tmp" "$SSL_CONF"
